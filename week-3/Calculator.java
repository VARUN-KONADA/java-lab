// overloading methods for airthemetic operations

public class Calculator
{
    int add(int a, int b)
    {
        return a + b;
    }
    double add(double a, double b)
    {
        return a + b;
    }
    int sub(int a, int b)
    {
        return a - b;
    }
    double sub(double a, double b)
    {
        return a - b;
    }
    int mul(int a, int b)
    {
        return a * b;
    }
    double mul(double a, double b)
    {
        return a * b;
    }
    int div(int a, int b)
    {
        return a / b;
    }
    double div(double a, double b)
    {
        return a / b;
    }
}